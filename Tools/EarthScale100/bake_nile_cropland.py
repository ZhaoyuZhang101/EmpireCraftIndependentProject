"""Aggregate ESA WorldCover 2021 cropland inside the Natural Earth Nile Delta."""
import argparse
import hashlib
import urllib.request
from pathlib import Path

import numpy as np
import rasterio
from rasterio.features import geometry_mask
from rasterio.windows import from_bounds
from shapely.geometry import shape

from bake_player_presets import ROOT
from bake_player_water import features


TILES = {
    "N30E027": "a286a019c9c6ec2e317256264a9c9cfd40033d4ef5a880056d4b69c02830c7d8",
    "N30E030": "7109008952637b4f7ecd17e03e25d28c0df14f741d5b9d7b553072cf8de616ee",
}
RESOLUTION = 20  # Geographic cells per degree. A source cell is 600 x 600 native pixels.


def aggregate(cache):
    region, = [f["geometry"] for f in features("geography_regions_polys", cache)
               if f["properties"]["NAME"] == "Nile Delta" and f["properties"]["FEATURECLA"] == "Delta"]
    west, south, east, north = shape(region).bounds
    x0, y0 = np.floor(np.array([west, south])*RESOLUTION).astype(int)
    x1, y1 = np.ceil(np.array([east, north])*RESOLUTION).astype(int)
    rows = np.zeros((y1-y0, x1-x0), dtype=np.uint8)
    for tile, checksum in TILES.items():
        filename = f"ESA_WorldCover_10m_2021_v200_{tile}_Map.tif"
        path = cache/filename
        if not path.exists():
            url = "https://esa-worldcover.s3.eu-central-1.amazonaws.com/v200/2021/map/"+filename
            with urllib.request.urlopen(url, timeout=180) as response:
                data = response.read()
            if hashlib.sha256(data).hexdigest() != checksum:
                raise ValueError(f"Downloaded WorldCover {tile} checksum mismatch")
            path.write_bytes(data)
        if hashlib.sha256(path.read_bytes()).hexdigest() != checksum:
            raise ValueError(f"Cached WorldCover {tile} checksum mismatch")
        with rasterio.open(path) as source:
            if source.crs.to_epsg() != 4326 or source.shape != (36000,36000):
                raise ValueError("Unexpected ESA WorldCover tile")
            left = max(x0, round(source.bounds.left*RESOLUTION))
            right = min(x1, round(source.bounds.right*RESOLUTION))
            for y in range(y0, y1):
                # Native class 40 is cropland. City, water, wetland and bare
                # pixels contribute to the area denominator without adding crop.
                window = from_bounds(left/RESOLUTION, y/RESOLUTION, right/RESOLUTION,
                                     (y+1)/RESOLUTION, source.transform).round_offsets().round_lengths()
                cover = source.read(1, window=window)
                inside = geometry_mask([region], cover.shape, source.window_transform(window), invert=True)
                crops = (inside & (cover == 40)).reshape(600, right-left, 600)
                rows[y-y0, left-x0:right-x0] = np.rint(15*crops.mean(axis=(0,2))).astype(np.uint8)
    return x0, y0, rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=ROOT/"ValidationOutput/BasinWater")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    args.cache.mkdir(exist_ok=True, parents=True)
    x0, y0, rows = aggregate(args.cache)
    strings = "".join('            "'+"".join(format(v,"x") for v in row)+'",\n' for row in rows)
    code = f"""// Generated by Tools/EarthScale100/bake_nile_cropland.py.
// ESA WorldCover 2021 v200 (CC BY 4.0) within Natural Earth v5.1.2's Nile Delta.
// South-first crop area fractions in fifteenths; see Examples/EarthScale100/NOTICE.txt.
namespace Orbis.Flat
{{
    internal static class FlatNileCropland
    {{
        internal const int SamplesPerDegree = {RESOLUTION}, West = {x0}, South = {y0};
        internal static readonly string[] Rows = {{
{strings}        }};
    }}
}}
"""
    path = ROOT/"Assets/ORBIS/Runtime/FlatWorld/Core/FlatNileCropland.cs"
    if args.check:
        if path.read_text(encoding="utf8") != code:
            raise ValueError("Nile cropland differs from the pinned land cover and delta boundary")
    else:
        path.write_text(code, encoding="utf8", newline="\n")
    print(f"{rows.shape[1]} x {rows.shape[0]} cells, {np.count_nonzero(rows)} with mapped cropland")


if __name__ == "__main__":
    main()
